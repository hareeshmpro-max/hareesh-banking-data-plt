from pathlib import Path
import pandas as pd

BASE = Path(__file__).resolve().parents[2]
DATA = BASE / "data" / "sample"
OUTPUT = BASE / "data" / "output"


def main():
    tx = pd.read_csv(DATA / "transactions.csv")
    accounts = pd.read_csv(DATA / "accounts.csv")

    # Apply the same business rules used by the analytics transformation.
    valid_account_ids = set(accounts["account_id"].dropna())

    source_success = tx[
        tx["status"].eq("SUCCESS")
        & tx["amount"].notna()
        & tx["amount"].gt(0)
        & tx["account_id"].isin(valid_account_ids)
    ].copy()

    source_count = len(source_success)
    source_amount = source_success["amount"].sum()

    # Read the analytics output generated by the transformation.
    target = pd.read_csv(
        OUTPUT / "monthly_customer_transactions.csv"
    )

    target_count = target["transaction_count"].sum()
    target_amount = target["transaction_amount"].sum()

    print("SOURCE TRANSACTION COUNT:", source_count)
    print("SOURCE TRANSACTION AMOUNT:", source_amount)

    print("\nTARGET TRANSACTION COUNT:", target_count)
    print("TARGET TRANSACTION AMOUNT:", target_amount)

    count_match = source_count == target_count
    amount_match = source_amount == target_amount

    print("\nRECONCILIATION RESULTS:")
    print("Transaction count match:", count_match)
    print("Transaction amount match:", amount_match)

    if count_match and amount_match:
        print("RECONCILIATION STATUS: PASS")
    else:
        print("RECONCILIATION STATUS: FAIL")
        raise ValueError("Source and target reconciliation failed.")

    print("\nRECONCILIATION RULES:")
    print("- SUCCESS transactions only")
    print("- Amount must be present and greater than 0")
    print("- Account ID must exist in account master")


if __name__ == "__main__":
    main()